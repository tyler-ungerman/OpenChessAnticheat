"""Empirical cohort calibration and Elo-fallback baselines.

The optional calibration file lives at ``data/baseline.json`` under the repository root and is
generated by ``scripts/build_baseline.py``.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any

import pandas as pd

PROJECT = Path(__file__).resolve().parents[3]
DEFAULT_BASELINE = PROJECT / "data" / "baseline.json"


_CACHED_CALIBRATION: dict[str, Any] | None = None


def build_empirical_baselines(
    control_features_df: pd.DataFrame,
) -> dict[tuple[str, int], dict[str, tuple[float, float]]]:
    """
    Build empirical (median, MAD_sigma) lookup tables per `(time_control, elo_bucket_100)`
    from control game rows.
    """
    if control_features_df.empty:
        return {}

    df = control_features_df.copy()
    df["elo_bucket"] = (pd.to_numeric(df["elo"], errors="coerce") // 100 * 100).fillna(-1).astype(int)

    metrics = [
        "capped_acpl",
        "top1_rate",
        "critical_top1_rate",
        "quiet_critical_top1_rate",
        "fast_critical_top1_rate",
        "choice_sensitivity_s",
        "mean_machine_surprise",
        "deep_only_top1_rate",
        "cv_move_time",
        "time_vs_eval_gap_corr",
        "opening_to_mid_acpl_drop",
        "deficit_acpl_drop",
        "scramble_acpl_drop",
    ]
    baselines: dict[tuple[str, int], dict[str, tuple[float, float]]] = {}

    for (tc, bucket), grp in df.groupby(["time_control", "elo_bucket"], sort=False):
        if len(grp) < 15:
            continue
        stats: dict[str, tuple[float, float]] = {}
        for col in metrics:
            if col not in grp.columns:
                continue
            clean = pd.to_numeric(grp[col], errors="coerce").dropna()
            if len(clean) < 10:
                continue
            med = float(clean.median())
            mad = float((clean - med).abs().median())
            sigma = (1.4826 * mad) if mad > 1e-6 else max(float(clean.std()), 1e-4)
            stats[col] = (round(med, 4), round(sigma, 4))
        baselines[(str(tc), int(bucket))] = stats

    return baselines


def load_calibration(
    baseline_path: Path = DEFAULT_BASELINE,
    force_reload: bool = False,
) -> dict[str, Any]:
    """
    Load empirical rating-bucket baselines and pooled `consistency_c` from
    ``data/baseline.json``. Cached in memory after first load.
    """
    global _CACHED_CALIBRATION
    if _CACHED_CALIBRATION is not None and not force_reload and baseline_path == DEFAULT_BASELINE:
        return _CACHED_CALIBRATION

    if not Path(baseline_path).is_file():
        return {"buckets": {}, "global_tc": {}, "consistency_c": 0.85, "n_clean_games": 0}

    payload = json.loads(Path(baseline_path).read_text(encoding="utf-8"))
    consistency_c = float((payload.get("pooled_fit") or {}).get("consistency_c") or 0.85)
    clean_rows = [r for r in payload.get("rows", []) if r.get("label", 0) == 0]

    records = []
    for r in clean_rows:
        tc = r.get("time_control") or r.get("tc") or "unknown"
        elo = r.get("rating") or r.get("elo")
        if elo is None or tc == "unknown":
            continue
        records.append(
            {
                "time_control": str(tc),
                "elo": float(elo),
                "capped_acpl": r.get("capped_acpl") if r.get("capped_acpl") is not None else r.get("acpl"),
                "top1_rate": (
                    r["best_move_rate_pct"] / 100.0
                    if r.get("best_move_rate_pct") is not None
                    else r.get("top1_rate")
                ),
                "critical_top1_rate": (
                    r["critical_best_rate_pct"] / 100.0
                    if r.get("critical_best_rate_pct") is not None
                    else r.get("critical_top1_rate")
                ),
                "choice_sensitivity_s": r.get("sensitivity_s") or r.get("choice_sensitivity_s"),
                "cv_move_time": (
                    r["move_time_sd_sec"] / r["mean_move_time_sec"]
                    if r.get("move_time_sd_sec") is not None
                    and r.get("mean_move_time_sec")
                    and r["mean_move_time_sec"] > 0
                    else r.get("cv_move_time")
                ),
            }
        )

    df = pd.DataFrame(records)
    buckets = build_empirical_baselines(df) if not df.empty else {}

    global_tc: dict[str, dict[str, tuple[float, float]]] = {}
    if not df.empty:
        for tc, grp in df.groupby("time_control", sort=False):
            stats: dict[str, tuple[float, float]] = {}
            for col in ("capped_acpl", "top1_rate", "critical_top1_rate", "choice_sensitivity_s", "cv_move_time"):
                clean = pd.to_numeric(grp[col], errors="coerce").dropna()
                if len(clean) >= 10:
                    med = float(clean.median())
                    mad = float((clean - med).abs().median())
                    sigma = (1.4826 * mad) if mad > 1e-6 else max(float(clean.std()), 1e-4)
                    stats[col] = (round(med, 4), round(sigma, 4))
            if stats:
                global_tc[str(tc)] = stats

    cal = {
        "buckets": buckets,
        "global_tc": global_tc,
        "consistency_c": consistency_c,
        "n_clean_games": len(df),
    }
    if baseline_path == DEFAULT_BASELINE:
        _CACHED_CALIBRATION = cal
    return cal


def _lookup_cohort_z(
    value: float | None,
    metric: str,
    tc: str,
    elo: float | None,
    calibration: dict[str, Any],
    higher_is_suspicious: bool = True,
) -> float | None:
    """Compute Z-score against the empirical control cohort for (time_control, 100-Elo bucket)."""
    if value is None or not math.isfinite(float(value)):
        return None
    buckets = calibration.get("buckets", {})
    global_tc = calibration.get("global_tc", {})

    stats_map = None
    if elo is not None and math.isfinite(float(elo)):
        target_bucket = int(float(elo)) // 100 * 100
        for offset in (0, -100, 100, -200, 200):
            candidate = buckets.get((tc, target_bucket + offset))
            if candidate and metric in candidate:
                stats_map = candidate
                break

    if stats_map is None:
        stats_map = global_tc.get(tc, {})

    if metric not in stats_map:
        return None

    med, sigma = stats_map[metric]
    z = (float(value) - med) / max(sigma, 1e-4)
    return z if higher_is_suspicious else -z


def _expected_acpl_for_elo(elo: float | None, time_control: str) -> float:
    """Fallback curve when neither personal history nor a control baseline is available."""
    rating = float(elo) if (elo is not None and math.isfinite(float(elo))) else 1500.0
    rating = max(400.0, min(2900.0, rating))
    base_acpl = 115.0 * math.exp(-0.00072 * (rating - 600.0)) + 12.0
    tc_multiplier = {"bullet": 1.22, "blitz": 1.08, "rapid": 1.00, "daily": 0.90}.get(time_control, 1.05)
    return base_acpl * tc_multiplier


def _expected_top1_for_elo(elo: float | None, time_control: str) -> float:
    """Fallback curve when neither personal history nor a control baseline is available."""
    rating = float(elo) if (elo is not None and math.isfinite(float(elo))) else 1500.0
    rating = max(400.0, min(2900.0, rating))
    base_top1 = 0.28 + 0.34 * ((rating - 400.0) / 2400.0)
    tc_offset = {"bullet": -0.04, "blitz": -0.02, "rapid": 0.0, "daily": 0.03}.get(time_control, 0.0)
    return max(0.15, min(0.75, base_top1 + tc_offset))
